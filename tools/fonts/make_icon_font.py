#!/usr/bin/env python3
"""Builds the editor icon font: a subset of Lucide (ISC) with only the icons listed in ICONS,
plus snk/gui/gui_icons.h with their UTF-8 strings and the codepoint range for the atlas.

Usage: python3 tools/fonts/make_icon_font.py <lucide-static package dir>
The package is lucide-static from npm (font/lucide.ttf, font/codepoints.json, LICENSE).
Needs fonttools (pip install fonttools). Run it again after changing ICONS and commit both outputs.
"""
import json
import pathlib
import shutil
import sys

from fontTools import subset

# name in the header -> Lucide icon name
ICONS = {
	"folder": "folder",
	"folder_open": "folder-open",
	"file": "file",
	"file_text": "file-text",
	"file_code": "file-code",
	"model": "box",
	"image": "image",
	"sound": "music",
	"desc": "scroll-text",
	"search": "search",
	"back": "arrow-left",
	"up": "arrow-up",
	"save": "save",
	"play": "play",
	"pause": "pause",
	"stop": "square",
	"add": "plus",
	"close": "x",
	"visible": "eye",
	"hidden": "eye-off",
	"lock": "lock",
	"settings": "settings",
	"layers": "layers",
	"camera": "camera",
	"sun": "sun",
	"light": "lightbulb",
	"move": "move",
	"rotate": "rotate-cw",
	"scale": "scaling",
	"remove": "trash-2",
	"refresh": "refresh-cw",
	"copy": "copy",
	"expand": "chevron-right",
	"collapse": "chevron-down",
	"warning": "triangle-alert",
	"info": "info",
	"error": "circle-x",
	"hierarchy": "list-tree",
}

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONT_OUT = ROOT / "core/res/fonts/lucide-icons.ttf"
LICENSE_OUT = ROOT / "core/res/fonts/lucide-LICENSE.txt"
HEADER_OUT = ROOT / "core/engine/gui/backends/interface/include/snk/gui/gui_icons.h"


def utf8_literal(cp: int) -> str:
	return "".join(f"\\x{b:02x}" for b in chr(cp).encode("utf-8"))


def main() -> int:
	if len(sys.argv) != 2:
		print(__doc__)
		return 2
	package = pathlib.Path(sys.argv[1])
	codepoints = json.loads((package / "font/codepoints.json").read_text(encoding="utf-8"))
	missing = [lucide for lucide in ICONS.values() if lucide not in codepoints]
	if missing:
		print("not in Lucide:", ", ".join(missing))
		return 1
	used = {name: codepoints[lucide] for name, lucide in ICONS.items()}

	options = subset.Options()
	options.notdef_outline = True
	options.name_IDs = ["*"]
	font = subset.load_font(str(package / "font/lucide.ttf"), options)
	subsetter = subset.Subsetter(options)
	subsetter.populate(unicodes=sorted(used.values()))
	subsetter.subset(font)
	subset.save_font(font, str(FONT_OUT), options)
	shutil.copyfile(package / "LICENSE", LICENSE_OUT)

	lines = [
		"#pragma once",
		"#include <imgui.h>",
		"",
		"// Generated by tools/fonts/make_icon_font.py from Lucide (ISC, core/res/fonts/lucide-LICENSE.txt); do not edit.",
		"namespace gui::icon",
		"{",
		f"\tinline constexpr ImWchar first = 0x{min(used.values()):04x};",
		f"\tinline constexpr ImWchar last = 0x{max(used.values()):04x};",
		"",
	]
	width = max(len(name) for name in used)
	for name, cp in sorted(used.items()):
		lines.append(f"\tinline constexpr char {name}[]{' ' * (width - len(name))} = \"{utf8_literal(cp)}\";")
	lines.append("}")
	HEADER_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
	print(f"{len(used)} icons -> {FONT_OUT.name} ({FONT_OUT.stat().st_size} bytes), {HEADER_OUT.name}")
	return 0


if __name__ == "__main__":
	sys.exit(main())
